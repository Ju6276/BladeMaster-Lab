"""Generate mesh-contact variants from the unchanged physical laws."""
import ast
from pathlib import Path

def generate():
 root=Path(__file__).parent
 trees={n:ast.parse((root/(n+".py")).read_text()) for n in ("contact","blade_constraint")}
 changed={"blade_query","resist_cut","blade_at","assign","count_embedded","prepare_at"}
 while True:
  new=changed.copy()
  for tree in trees.values():
   for node in tree.body:
    if isinstance(node,ast.FunctionDef) and any(isinstance(c,ast.Call) and isinstance(c.func,ast.Name) and c.func.id in changed for c in ast.walk(node)):
     new.add(node.name)
  if new==changed:break
  changed=new
 def replace(text,old,new):
  if old not in text:raise ValueError("Missing template: "+old)
  return text.replace(old,new)
 class Convert(ast.NodeTransformer):
  def visit_ImportFrom(self,node):
   if node.module in trees:node.module="mesh_"+node.module
   return node
  def visit_Call(self,node):
   self.generic_visit(node)
   if isinstance(node.func,ast.Name) and node.func.id in changed:
    node.args.append(ast.Name(id="geometry",ctx=ast.Load()))
   return node
  def visit_FunctionDef(self,node):
   self.generic_visit(node)
   if node.name in changed:node.args.args.append(ast.arg(arg="geometry",annotation=ast.Name(id="MeshTool",ctx=ast.Load())))
   if node.name=="blade_query":
    node.body=ast.parse("return mesh_query(local, geometry)").body
   if node.name in ("resist_cut","blade_at","assign","count_embedded","prepare_at"):
    text=ast.unparse(ast.Module(body=node.body,type_ignores=[]))
    if node.name=="resist_cut":
     text=replace(text,"edge = origin + wp.quat_rotate(q, wp.vec3(0.0, 0.0, -half[2]))","particle_local = wp.quat_rotate_inv(q, x[p] - origin)\nedge_local, edge_inside = edge_at(particle_local[1], geometry)\nedge = origin + wp.quat_rotate(q, edge_local)")
     text=replace(text,"wp.abs(local_edge[1]) <= half[1]","edge_inside")
    if node.name=="blade_at":
     text=replace(text,"blade_radius = wp.length(half)","blade_radius = geometry.radius")
     text=replace(text,"front = -half[2] - local[2]","edge_local, edge_inside = edge_at(local[1], geometry)\n    front = edge_local[2] - local[2]")
     text=replace(text,"wp.abs(local[1]) <= half[1]","edge_inside")
     text=replace(text,"wp.vec3(local[0], local[1], -half[2])","wp.vec3(local[0], local[1], edge_local[2])")
     text=replace(text,"wp.abs(normal_local[1]) < 1e-06 and wp.abs(normal_local[2]) < 1e-06","wp.abs(normal_local[0]) > 0.9")
    if node.name=="assign":
     text=replace(text,"edge = tool_pos[0] + wp.quat_rotate(tool_rot[0], wp.vec3(0.0, 0.0, -half[2]))","particle_local = wp.quat_rotate_inv(tool_rot[0], xp - tool_pos[0])\nedge_local, edge_inside = edge_at(particle_local[1], geometry)\nedge = tool_pos[0] + wp.quat_rotate(tool_rot[0], edge_local)")
     text=replace(text,"edge_here = edge + wp.quat_rotate(tool_rot[0], wp.vec3(0.0, local[1], 0.0))","edge_here = edge")
     text=replace(text,"wp.abs(local[1]) <= half[1]","edge_inside")
    if node.name=="count_embedded":
     text=replace(text,"if wp.abs(local[0]) <= 6.0 * spacing and wp.abs(local[1]) <= half[1] and (wp.abs(local[2]) <= half[2]):","closest, normal, distance = mesh_query(local, geometry)\nif distance <= 6.0 * spacing:")
    if node.name=="prepare_at":
     text=replace(text,"if wp.abs(local[1]) >= half[1] or local[2] <= -half[2] + bevel or local[2] >= half[2]:","edge_local, edge_inside = edge_at(local[1], geometry)\nif not edge_inside or local[2] <= edge_local[2]:")
     text=replace(text,"n = wp.quat_rotate(rotation[0], wp.vec3(s, 0.0, 0.0))\ngap = s * local[0] - half[0]\narm = wp.quat_rotate(rotation[0], wp.vec3(s * half[0], local[1], local[2]))","surface, local_normal, found = side_surface(local, s, geometry)\nif not found:\n    side[p] = 0.0\n    return\nn = wp.quat_rotate(rotation[0], local_normal)\ngap = wp.dot(local - surface, local_normal)\narm = wp.quat_rotate(rotation[0], surface)")
    node.body=ast.parse(text).body
   return node
 for name,tree in trees.items():
  tree=Convert().visit(tree);ast.fix_missing_locations(tree)
  text=ast.unparse(tree).replace("import warp as wp","import warp as wp\nfrom .mesh_geometry import MeshTool, mesh_query, edge_at, side_surface",1)
  (root/("mesh_"+name+".py")).write_text("# Generated by generate_mesh_kernels.py; edit the generator.\n"+text+"\n")
 from . import generate_batch_kernels as batch
 old=batch.NAMES
 batch.NAMES=("material","mesh_contact","mesh_blade_constraint")
 try:batch.generate()
 finally:batch.NAMES=old
if __name__=="__main__":generate()
