"""Generate explicit-profile variants; legacy kernels remain unchanged."""

import ast
from pathlib import Path


def generate():
    root = Path(__file__).parent
    trees = {
        name: ast.parse((root / (name + ".py")).read_text())
        for name in ("contact", "tool", "blade_constraint")
    }
    changed = set()
    for tree in trees.values():
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and any(a.arg == "bevel" for a in node.args.args):
                changed.add(node.name)

    class Convert(ast.NodeTransformer):
        def visit_ImportFrom(self, node):
            if node.module in trees:
                node.module = "profile_" + node.module
            return node

        def visit_FunctionDef(self, node):
            self.generic_visit(node)
            if node.name in changed:
                node.args.args.append(ast.arg(arg="neck", annotation=ast.Name(id="float", ctx=ast.Load())))
            if node.name == "blade_query":
                node.body = ast.parse("return profile_query(local, half, bevel, neck)").body
            return node

        def visit_Call(self, node):
            self.generic_visit(node)
            if isinstance(node.func, ast.Name) and node.func.id in changed:
                node.args.append(ast.Name(id="neck", ctx=ast.Load()))
            return node

    for name, tree in trees.items():
        tree = Convert().visit(tree)
        ast.fix_missing_locations(tree)
        text = ast.unparse(tree)
        if name == "contact":
            text = text.replace(
                "wp.abs(normal_local[1]) < 1e-06 and wp.abs(normal_local[2]) < 1e-06",
                "wp.abs(normal_local[1]) < 1e-06 and wp.abs(normal_local[0]) > 0.9",
            )
            text = text.replace(
                "import warp as wp", "import warp as wp\nfrom .profile_geometry import profile_query", 1
            )
        if name == "tool":
            text = text.replace("if j == 1:\n        x = half[0]", "if j == 1:\n        x = neck").replace(
                "elif j == 4:\n        x = -half[0]", "elif j == 4:\n        x = -neck"
            )
            text = text.replace(
                "wp.vec3(-half[0], y, -half[2] + bevel)", "wp.vec3(-neck, y, -half[2] + bevel)"
            )
            text = text.replace("wp.vec3(half[0], y, -half[2] + bevel)", "wp.vec3(neck, y, -half[2] + bevel)")
        if name == "blade_constraint":
            old = "n = wp.quat_rotate(rotation[0], wp.vec3(s, 0.0, 0.0))\n    gap = s * local[0] - half[0]\n    arm = wp.quat_rotate(rotation[0], wp.vec3(s * half[0], local[1], local[2]))"
            new = "slope = (half[0] - neck) / (2.0 * half[2] - bevel)\n    width = neck + slope * (local[2] + half[2] - bevel)\n    local_normal = wp.normalize(wp.vec3(s, 0.0, -slope))\n    n = wp.quat_rotate(rotation[0], local_normal)\n    gap = (s * local[0] - width) / wp.sqrt(1.0 + slope * slope)\n    arm = wp.quat_rotate(rotation[0], local - gap * local_normal)"
            assert old in text
            text = text.replace(old, new)
        (root / ("profile_" + name + ".py")).write_text(
            "# Generated by generate_profile_kernels.py; edit the generator.\n" + text + "\n"
        )
    from . import generate_batch_kernels

    old = generate_batch_kernels.NAMES
    generate_batch_kernels.NAMES = ("material", "profile_contact", "profile_tool", "profile_blade_constraint")
    try:
        generate_batch_kernels.generate()
    finally:
        generate_batch_kernels.NAMES = old


if __name__ == "__main__":
    generate()
